def wiki(route):
    from urllib.parse import urlparse,parse_qs
    q=parse_qs(urlparse(route.request.url).query).get('gsrsearch',['x'])[0]
    body=json.dumps({"query":{"pages":{"1":{"title":q,"thumbnail":{"source":IMG},"extract":"A well known university."}}}})
    route.fulfill(status=200,content_type="application/json",headers={"access-control-allow-origin":"*"},body=body)
